// סיווג לפי מילון בלבד. מצרך לא מוכר מקבל "אחר".
export function categorize(name: string): string {
  const text = name.trim();
  for (const cat of CATEGORIES) {
    if (cat.keywords.some((k) => text.includes(k))) return cat.name;
  }
  return OTHER;
}